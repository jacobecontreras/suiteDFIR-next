/// An encrypted iTunes backup with its password, a keychain, custom modules and an explicit
/// timezone: the recorded argv has `<redacted>` after `--itunes_password`, and the password is in
/// no file of the run folder.
#[test]
fn z0_itunes_password() {
    let lab = Lab::new();
    let backup = lab.root.path().join("ev").join("bk");
    lab.itunes_backup(&backup, true);
    let keychain = lab.root.path().join("ev").join("keychain-2.db");
    fs::write(&keychain, b"keychain bytes").unwrap();
    let mut request = lab.request(ToolId::Ileapp, &backup, InputType::Itunes);
    request.itunes_password = Some(PASSWORD.to_owned());
    request.keychain_path = Some(keychain.to_string_lossy().into_owned());
    request.timezone = Some("Europe/Berlin".to_owned());
    request.modules = ModuleSelection::Custom {
        modules: vec!["sms".to_owned(), "callHistory".to_owned()],
    };
    let ran = run(&lab, ToolId::Ileapp, "success", request, false);
    assert_eq!(
        ran.outcome.record.options.keychain_sha256.as_deref(),
        Some(sha256_hex(b"keychain bytes").as_str())
    );
    let dir = run_dir(&ran);
    let mut pending = vec![dir.clone()];
    while let Some(folder) = pending.pop() {
        for entry in fs::read_dir(&folder).unwrap() {
            let path = entry.unwrap().path();
            if path.is_dir() {
                pending.push(path);
            } else {
                let bytes = fs::read(&path).unwrap();
                assert!(
                    !bytes
                        .windows(PASSWORD.len())
                        .any(|w| w == PASSWORD.as_bytes()),
                    "{} holds the password",
                    path.display()
                );
            }
        }
    }
    let mut goldens = Goldens::default();
    check_run(&mut goldens, "itunes_password", &lab, &ran, true, true);
    check_files(
        &mut goldens,
        "itunes_password",
        &ran,
        &["profile.ilprofile"],
    );
    goldens.finish();
}

