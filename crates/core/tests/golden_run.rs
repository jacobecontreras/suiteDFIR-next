/// App dirs, a known case and an `fs` input folder, all in a short-named temp dir (the Windows test
/// machine has long paths disabled).
struct Lab {
    root: tempfile::TempDir,
    paths: AppPaths,
    settings: Settings,
    case: CreatedCase,
    input: PathBuf,
}

impl Lab {
    fn new() -> Self {
        let root = tempfile::Builder::new().prefix("sdz").tempdir().unwrap();
        let paths = AppPaths {
            app_data: root.path().join("data"),
            app_config: root.path().join("config"),
            app_cache: root.path().join("cache"),
            app_log: root.path().join("log"),
        };
        let cases = root.path().join("cases");
        fs::create_dir_all(&cases).unwrap();
        let case = case::create(&cases, &examples::case_fields()).unwrap();
        let mut settings = settings::defaults(&cases);
        settings::touch_recent(&mut settings, &case.path.to_string_lossy());
        let input = root.path().join("ev").join("fs");
        fs::create_dir_all(&input).unwrap();
        fs::write(input.join("evidence.txt"), "evidence").unwrap();
        Self {
            root,
            paths,
            settings,
            case,
            input,
        }
    }

    /// fake-leapp as the dev-override `tool`, in `scenario`, 20 lines 5 ms apart.
    fn context(&self, tool: ToolId, scenario: &str) -> RunContext {
        let manifest = &manifest::embedded().unwrap().tools[&tool];
        let prepared = runner::dev_override_tool(
            Path::new(FAKE_LEAPP),
            tool,
            manifest,
            manifest::host_platform(),
        )
        .unwrap();
        let env: Vec<(OsString, OsString)> = vec![
            ("FAKE_LEAPP_SCENARIO".into(), scenario.into()),
            ("FAKE_LEAPP_INTERVAL_MS".into(), "5".into()),
            ("FAKE_LEAPP_LINES".into(), "20".into()),
        ];
        RunContext {
            paths: self.paths.clone(),
            settings: self.settings.clone(),
            case_dir: self.case.path.clone(),
            case: self.case.case.clone(),
            host: host(),
            tool: prepared,
            env,
            max_run_dir_chars: runner::default_run_dir_limit(),
        }
    }

    fn request(&self, tool: ToolId, input: &Path, input_type: InputType) -> RunRequest {
        RunRequest {
            case_path: self.case.path.to_string_lossy().into_owned(),
            tool,
            input_path: input.to_string_lossy().into_owned(),
            input_type,
            modules: ModuleSelection::All,
            timezone: None,
            itunes_password: None,
            keychain_path: None,
            hash_input: false,
            label: Some("Golden run".to_owned()),
        }
    }

    fn fs_request(&self, tool: ToolId) -> RunRequest {
        self.request(tool, &self.input, InputType::Fs)
    }

    /// The case's run folders.
    fn run_dirs(&self) -> Vec<PathBuf> {
        fs::read_dir(self.case.path.join("runs"))
            .map(|entries| entries.map(|e| e.unwrap().path()).collect())
            .unwrap_or_default()
    }

    /// An iTunes-style backup folder at `dir` (`Manifest.plist` with `IsEncrypted`).
    fn itunes_backup(&self, dir: &Path, encrypted: bool) {
        fs::create_dir_all(dir).unwrap();
        let plist = format!(
            "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<plist version=\"1.0\"><dict>\
             <key>IsEncrypted</key><{encrypted}/></dict></plist>\n"
        );
        fs::write(dir.join("Manifest.plist"), plist).unwrap();
        fs::write(dir.join("Manifest.db"), b"SQLite format 3\0").unwrap();
    }

    /// A file input `image.zip` with fixed contents (detected as `zip`).
    fn file_input(&self) -> PathBuf {
        let path = self.root.path().join("ev").join("image.zip");
        fs::create_dir_all(path.parent().unwrap()).unwrap();
        fs::write(&path, FILE_INPUT.repeat(1000)).unwrap();
        path
    }

    /// No per-run temp dir is left in `<app_cache>/tmp`.
    fn assert_no_temp_dirs(&self) {
        let left: Vec<_> = fs::read_dir(self.paths.temp_root())
            .map(|entries| entries.map(|e| e.unwrap().file_name()).collect())
            .unwrap_or_default();
        assert!(left.is_empty(), "left in the temp root: {left:?}");
    }
}

/// The hashed file input is this, 1000 times.
const FILE_INPUT: &[u8] = b"Z0a2 file input\n";

/// A run that went to its end.
struct Ran {
    outcome: RunOutcome,
    /// `run.json` right after `RunJob::prepare` (lifecycle step 2).
    initial: Option<String>,
    /// LEAPP's process id (the bootloader's), from the `running` phase on.
    pid: Option<u32>,
}

/// Runs a started job to the end: step 2 (`prepare`), then the rest. With `cancel`, the run is
/// cancelled when the first log batch arrives.
fn finish_job(job: RunJob, cancel: bool) -> Ran {
    let run_dir = job.run_dir().to_path_buf();
    let control = job.control();
    let mut pid = None;
    let mut cancelled = false;
    let mut emit = |event: RunEvent| match event {
        RunEvent::Phase {
            phase: RunPhase::Running,
        } => pid = control.process_id(),
        RunEvent::Log { .. } if cancel && !cancelled => {
            cancelled = true;
            control.cancel();
        }
        _ => {}
    };
    let prepared = job.prepare(&mut emit);
    let initial = fs::read_to_string(run_dir.join("run.json")).ok();
    let outcome = prepared.run(&mut emit);
    assert_eq!(cancelled, cancel, "the cancel was requested");
    assert_eq!(outcome.write_error, None);
    Ran {
        outcome,
        initial,
        pid,
    }
}

fn run(lab: &Lab, tool: ToolId, scenario: &str, request: RunRequest, cancel: bool) -> Ran {
    let job = runner::start(request, lab.context(tool, scenario)).unwrap();
    finish_job(job, cancel)
}

fn run_dir(ran: &Ran) -> PathBuf {
    PathBuf::from(&ran.outcome.summary.run_dir)
}

