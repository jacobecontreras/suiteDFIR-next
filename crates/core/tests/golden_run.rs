/// `text` as it appears inside a JSON string.
fn escaped(text: &str) -> String {
    let quoted = serde_json::to_string(text).unwrap();
    quoted[1..quoted.len() - 1].to_owned()
}

/// `YYYY-MM-DDTHH:MM:SSZ`.
fn is_timestamp(text: &str) -> bool {
    let bytes = text.as_bytes();
    bytes.len() == 20
        && bytes.iter().enumerate().all(|(i, b)| match i {
            4 | 7 => *b == b'-',
            10 => *b == b'T',
            13 | 16 => *b == b':',
            19 => *b == b'Z',
            _ => b.is_ascii_digit(),
        })
}

/// The end (exclusive) of the JSON string starting at `start` (its opening quote).
fn string_end(bytes: &[u8], start: usize) -> usize {
    let mut i = start + 1;
    loop {
        match bytes[i] {
            b'\\' => i += 2,
            b'"' => return i + 1,
            _ => i += 1,
        }
    }
}

/// Lowercase hex SHA-256, computed here with `sha2` (never through the code under test).
fn sha256_hex(bytes: &[u8]) -> String {
    format!("{:x}", Sha256::digest(bytes))
}

/// Normalizes JSON text (see the module doc).
struct Normalizer {
    /// Run-specific strings, JSON-escaped, and their tokens; applied in order.
    subs: Vec<(String, &'static str)>,
    /// `(parent key, key, raw JSON value, token)`: exactly that value at that place becomes the
    /// token (a JSON string).
    values: Vec<(&'static str, &'static str, String, &'static str)>,
}

impl Normalizer {
    fn new() -> Self {
        Self {
            subs: Vec::new(),
            values: Vec::new(),
        }
    }

    fn sub(&mut self, text: &str, token: &'static str) -> &mut Self {
        self.subs.push((escaped(text), token));
        self
    }

    fn value(&mut self, parent: &'static str, key: &'static str, raw: String, token: &'static str) {
        self.values.push((parent, key, raw, token));
    }

    fn normalize(&self, path: &[String], raw: &str) -> String {
        let key = path.last().map_or("", String::as_str);
        let parent = path.len().checked_sub(2).map_or("", |i| path[i].as_str());
        if key == "duration_ms" {
            return if raw.parse::<u64>().is_ok() {
                "\"<DURATION_MS>\"".to_owned()
            } else {
                raw.to_owned()
            };
        }
        for (p, k, value, token) in &self.values {
            if *p == parent && *k == key && value == raw {
                return format!("\"{token}\"");
            }
        }
        if !raw.starts_with('"') {
            return raw.to_owned();
        }
        if parent == "app" && key == "version" && raw == format!("\"{APP_VERSION}\"") {
            return "\"<APP_VERSION>\"".to_owned();
        }
        let mut text = raw.to_owned();
        for (from, to) in &self.subs {
            text = text.replace(from.as_str(), to);
        }
        if is_timestamp(&text[1..text.len() - 1]) {
            return "\"<TIMESTAMP>\"".to_owned();
        }
        text
    }

    /// Normalizes JSON text, keeping everything else (layout, key order) byte for byte.
    fn json(&self, text: &str) -> String {
        let bytes = text.as_bytes();
        let mut out = String::with_capacity(text.len());
        // The key of each open object (`[]` for arrays), and whether a key comes next.
        let mut path: Vec<String> = Vec::new();
        let mut objects: Vec<bool> = Vec::new();
        let mut want_key = false;
        let mut i = 0;
        while i < bytes.len() {
            match bytes[i] {
                b'{' | b'[' => {
                    let object = bytes[i] == b'{';
                    objects.push(object);
                    path.push(if object {
                        String::new()
                    } else {
                        "[]".to_owned()
                    });
                    want_key = object;
                    out.push(char::from(bytes[i]));
                    i += 1;
                }
                b'}' | b']' => {
                    objects.pop();
                    path.pop();
                    want_key = false;
                    out.push(char::from(bytes[i]));
                    i += 1;
                }
                b',' => {
                    want_key = objects.last() == Some(&true);
                    out.push(',');
                    i += 1;
                }
                b'"' => {
                    let end = string_end(bytes, i);
                    let raw = &text[i..end];
                    if want_key {
                        *path.last_mut().unwrap() = serde_json::from_str(raw).unwrap();
                        want_key = false;
                        out.push_str(raw);
                    } else {
                        out.push_str(&self.normalize(&path, raw));
                    }
                    i = end;
                }
                b':' | b' ' | b'\n' | b'\r' | b'\t' => {
                    out.push(char::from(bytes[i]));
                    i += 1;
                }
                _ => {
                    let end = bytes[i..]
                        .iter()
                        .position(|b| matches!(b, b',' | b'}' | b']') || b.is_ascii_whitespace())
                        .map_or(bytes.len(), |n| i + n);
                    out.push_str(&self.normalize(&path, &text[i..end]));
                    i = end;
                }
            }
        }
        out
    }
}

fn pretty<T: Serialize>(value: &T) -> String {
    let mut text = serde_json::to_string_pretty(value).unwrap();
    text.push('\n');
    text
}

