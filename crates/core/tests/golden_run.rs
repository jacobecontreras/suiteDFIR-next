/// Whether `id` is `YYYYMMDD-HHMMSSZ-<tool>-<6 lowercase hex>` stamped at `created_at`.
fn assert_run_id(id: &str, tool: ToolId, created_at: &str) {
    let stamp: String = created_at.chars().filter(|c| c.is_ascii_digit()).collect();
    let expected_prefix = format!("{}-{}Z-{tool}-", &stamp[..8], &stamp[8..]);
    let random = id.strip_prefix(&expected_prefix).unwrap_or_else(|| {
        panic!("run id {id} does not start with {expected_prefix}");
    });
    assert!(
        random.len() == 6
            && random
                .bytes()
                .all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b)),
        "{id}"
    );
}

/// The regular files under `dir`, relative to `base` with `/` separators.
fn regular_files(base: &Path, dir: &Path) -> Vec<String> {
    let mut files = Vec::new();
    let mut pending = vec![dir.to_path_buf()];
    while let Some(folder) = pending.pop() {
        for entry in fs::read_dir(&folder).unwrap() {
            let path = entry.unwrap().path();
            let meta = fs::symlink_metadata(&path).unwrap();
            if meta.is_dir() {
                pending.push(path);
            } else if meta.is_file() {
                let rel = path.strip_prefix(base).unwrap();
                let parts: Vec<String> = rel
                    .components()
                    .map(|c| c.as_os_str().to_string_lossy().into_owned())
                    .collect();
                files.push(parts.join("/"));
            }
        }
    }
    files.sort();
    files
}

/// A manifest path as written (GNU `sha256sum` escaping undone).
fn unescape(name: &str) -> String {
    let mut out = String::new();
    let mut chars = name.chars();
    while let Some(c) = chars.next() {
        if c == '\\' {
            match chars.next() {
                Some('\\') => out.push('\\'),
                Some('n') => out.push('\n'),
                Some('r') => out.push('\r'),
                other => panic!("bad escape {other:?} in {name:?}"),
            }
        } else {
            out.push(c);
        }
    }
    out
}

/// What the check of `report.sha256` found.
struct Manifest {
    /// SHA-256 of the manifest file.
    sha256: String,
    /// Bytes of the files it lists, read from disk.
    total_bytes: u64,
    lines: u64,
}

/// Checks `report.sha256` (when the run wrote one): every line's hash against `sha2` over its
/// file, exactly the regular files under `report/` listed; then its golden with the hashes
/// replaced. A manifest must be written exactly when its golden exists.
fn check_manifest(goldens: &mut Goldens, name: &str, dir: &Path) -> Option<Manifest> {
    let golden = format!("{name}.report.sha256");
    let bytes = match fs::read(dir.join("report.sha256")) {
        Ok(bytes) => bytes,
        Err(e) if e.kind() == io::ErrorKind::NotFound => {
            if Goldens::file(&golden).is_file() {
                eprintln!(
                    "---- z0a2 golden mismatch: {golden} on {}: the golden exists, but no \
                     report.sha256 was written ----",
                    os_name()
                );
                goldens.mismatches.push(golden);
            }
            return None;
        }
        Err(e) => panic!("report.sha256: {e}"),
    };
    let text = String::from_utf8(bytes.clone()).unwrap();
    let mut normalized = String::new();
    let mut listed = Vec::new();
    let mut total_bytes = 0u64;
    for line in text.split_inclusive('\n') {
        let body = line.strip_suffix('\n').expect("LF line endings");
        let (prefix, rest) = match body.strip_prefix('\\') {
            Some(rest) => ("\\", rest),
            None => ("", body),
        };
        let (hash, name_part) = rest.split_at(64);
        let written = name_part.strip_prefix("  ").expect("two spaces");
        let rel = if prefix.is_empty() {
            written.to_owned()
        } else {
            unescape(written)
        };
        let file = rel
            .split('/')
            .fold(dir.to_path_buf(), |path, part| path.join(part));
        let contents = fs::read(&file).unwrap();
        assert_eq!(hash, sha256_hex(&contents), "{rel}");
        total_bytes += contents.len() as u64;
        listed.push(rel);
        normalized.push_str(prefix);
        normalized.push_str("<SHA256>  ");
        normalized.push_str(written);
        normalized.push('\n');
    }
    let mut sorted = listed.clone();
    sorted.sort();
    assert_eq!(sorted, regular_files(dir, &dir.join("report")));
    goldens.check(&golden, &normalized);
    Some(Manifest {
        sha256: sha256_hex(&bytes),
        total_bytes,
        lines: listed.len() as u64,
    })
}

/// The normalizer for the records of `ran` in `lab` (see the module doc).
fn normalizer(lab: &Lab, ran: &Ran, manifest: Option<&Manifest>) -> Normalizer {
    let mut normalizer = Normalizer::new();
    let fake = std::path::absolute(FAKE_LEAPP).unwrap();
    normalizer
        .sub(&fake.to_string_lossy(), "<FAKE_LEAPP>")
        .sub(&lab.root.path().to_string_lossy(), "<LAB>")
        .sub(&ran.outcome.record.run_id, "<RUN_ID>")
        .sub(&lab.case.case.case_id, "<CASE_ID>")
        .sub(
            &sha256_hex(&fs::read(FAKE_LEAPP).unwrap()),
            "<FAKE_LEAPP_SHA256>",
        );
    if let Some(manifest) = manifest {
        normalizer.sub(&manifest.sha256, "<MANIFEST_SHA256>");
        normalizer.value(
            "seal",
            "total_bytes",
            manifest.total_bytes.to_string(),
            "<TOTAL_BYTES>",
        );
    }
    if let Some(pid) = ran.pid {
        normalizer
            .sub(&format!("PYI-{pid}:"), "PYI-<PID>:")
            .sub(&format!("_MEIfake{pid}"), "_MEIfake<PID>");
    }
    if let Some(platform) = manifest::host_platform() {
        normalizer.value(
            "tool",
            "platform",
            serde_json::to_string(&platform).unwrap(),
            "<PLATFORM>",
        );
    }
    normalizer
}

/// The goldens of one run: `<name>.run.json`, `<name>.report.sha256` (exactly when a report was
/// sealed; with `manifest` false, `report.sha256` is not a manifest of this run) and, with
/// `initial`, `<name>.initial.run.json`. Also: the record on disk is the outcome's, final and
/// read-only; its run id and duration fit its times; no temp dir is left.
fn check_run(
    goldens: &mut Goldens,
    name: &str,
    lab: &Lab,
    ran: &Ran,
    manifest: bool,
    initial: bool,
) {
    let dir = run_dir(ran);
    let record = &ran.outcome.record;
    let found = if manifest {
        check_manifest(goldens, name, &dir)
    } else {
        None
    };
    if let Some(found) = &found {
        assert_eq!(record.output.seal.file_count, Some(found.lines));
    }
    let text = fs::read_to_string(dir.join("run.json")).unwrap();
    let on_disk: RunRecord = parse_versioned(text.as_bytes()).unwrap();
    assert_eq!(&on_disk, record);
    assert!(
        fs::metadata(dir.join("run.json"))
            .unwrap()
            .permissions()
            .readonly()
    );
    assert_eq!(dir.file_name().unwrap().to_string_lossy(), record.run_id);
    assert_run_id(
        &record.run_id,
        record.tool.id,
        &record.created_at.to_string(),
    );
    let ended = record.ended_at.expect("finalized").as_datetime();
    let expected_ms = (ended - record.created_at.as_datetime()).whole_milliseconds();
    assert_eq!(record.duration_ms.map(i128::from), Some(expected_ms));
    let normalizer = normalizer(lab, ran, found.as_ref());
    goldens.check(&format!("{name}.run.json"), &normalizer.json(&text));
    if initial {
        let text = ran.initial.as_deref().expect("the initial run.json");
        let first: RunRecord = parse_versioned(text.as_bytes()).unwrap();
        assert_eq!(first.status, RunStatus::Running);
        assert_eq!(first.output.seal, unsealed(SealStatus::Pending));
        goldens.check(&format!("{name}.initial.run.json"), &normalizer.json(text));
    }
    lab.assert_no_temp_dirs();
}

