#[derive(Serialize)]
struct Refusal {
    case: &'static str,
    error: AppError,
    /// Run folders in the case afterwards.
    run_folders: usize,
}

/// `run_start` refusals (lifecycle step 1): the exact `AppError`, and no run folder (so no
/// `run.json`). `password_required` for an encrypted iTunes backup (also with an empty password)
/// and for one whose encryption cannot be read; the argv path check (E7) for an empty input path
/// and for a `\\?\` path.
#[test]
fn z0_start_refusals() {
    let lab = Lab::new();
    let ev = lab.root.path().join("ev");
    let encrypted = ev.join("bk");
    lab.itunes_backup(&encrypted, true);
    // A Manifest.db without Manifest.plist: still a backup, encryption unknown.
    let unknown = ev.join("no-plist");
    fs::create_dir_all(&unknown).unwrap();
    fs::write(unknown.join("Manifest.db"), b"SQLite format 3\0").unwrap();
    let special = if cfg!(windows) {
        r"\\?\C:\evidence"
    } else {
        "//?/C:/evidence"
    };

    let itunes = |dir: &Path, password: Option<&str>| {
        let mut request = lab.request(ToolId::Ileapp, dir, InputType::Itunes);
        request.itunes_password = password.map(str::to_owned);
        request
    };
    let cases: Vec<(&'static str, RunRequest)> = vec![
        (
            "encrypted_backup_without_password",
            itunes(&encrypted, None),
        ),
        (
            "encrypted_backup_with_an_empty_password",
            itunes(&encrypted, Some("")),
        ),
        ("backup_with_unknown_encryption", itunes(&unknown, None)),
        (
            "empty_input_path",
            lab.request(ToolId::Ileapp, Path::new(""), InputType::Fs),
        ),
        (
            "special_prefix_input_path",
            lab.request(ToolId::Ileapp, Path::new(special), InputType::Fs),
        ),
    ];
    let mut refusals = Vec::new();
    for (case, request) in cases {
        let error = runner::start(request, lab.context(ToolId::Ileapp, "success")).unwrap_err();
        refusals.push(Refusal {
            case,
            error,
            run_folders: lab.run_dirs().len(),
        });
    }
    assert!(!lab.case.path.join("runs").exists());
    let mut normalizer = Normalizer::new();
    normalizer.sub(&lab.root.path().to_string_lossy(), "<LAB>");
    let mut goldens = Goldens::default();
    goldens.check("start-refusals.json", &normalizer.json(&pretty(&refusals)));
    goldens.finish();
}

/// A keychain file whose metadata can be read but whose contents cannot (mode 000; E14): the
/// exact `AppError`, and no run folder. Skipped (with a message) when running with privileges
/// that bypass file permissions.
#[cfg(unix)]
#[test]
fn z0_unreadable_keychain() {
    use std::os::unix::fs::PermissionsExt;

    use suitedfir_core::contracts::ErrorCode;

    let lab = Lab::new();
    let keychain = lab.root.path().join("ev").join("keychain.db");
    fs::write(&keychain, b"keychain bytes").unwrap();
    fs::set_permissions(&keychain, fs::Permissions::from_mode(0o000)).unwrap();
    if fs::File::open(&keychain).is_ok() {
        eprintln!("SKIPPED: running with privileges that bypass file permissions (root)");
        fs::set_permissions(&keychain, fs::Permissions::from_mode(0o644)).unwrap();
        return;
    }
    let mut request = lab.fs_request(ToolId::Ileapp);
    request.keychain_path = Some(keychain.to_string_lossy().into_owned());
    let error = runner::start(request, lab.context(ToolId::Ileapp, "success")).unwrap_err();
    fs::set_permissions(&keychain, fs::Permissions::from_mode(0o644)).unwrap();
    assert!(lab.run_dirs().is_empty());
    let absolute = keychain.to_string_lossy().into_owned();
    let detail = error.detail.clone().unwrap_or_default();
    assert!(detail.starts_with(&format!("{absolute}: ")), "{detail}");
    assert_eq!(
        error,
        AppError {
            code: ErrorCode::PermissionDenied,
            message: "The keychain file could not be read".to_owned(),
            detail: Some(format!("{absolute}: Permission denied (os error 13)")),
        }
    );
}
