//! Z0a2 run goldens: the behavior baseline of the simplification pass (SIMPLIFY.md §3),
//! characterized on main 5c787b7 with fake-leapp through the stable entry points
//! (`runner::start`, `RunJob::prepare` + `PreparedRun::run`, the contract types).
//!
//! - A normalized golden `run.json` for every CONTRACTS.md §7.4 row (`slow` and `ignore_term`
//!   cancelled on the first log batch; `ignore_term` on Unix only), `glibc_too_old` for iLEAPP and
//!   aLEAPP, an aLEAPP `success`, a hashed single-file input, an iLEAPP `itunes` run with a
//!   password (the redacted argv, with a keychain, custom modules and an explicit timezone),
//!   `prepare_failed` and a seal that fails (E2).
//! - The initial `run.json` (read right after `RunJob::prepare`) of four of them.
//! - The normalized `report.sha256` of every run that sealed a report.
//! - The `run_start` refusals: `password_required` and the argv path check (E7), each an exact
//!   `AppError` that creates no run folder; an unreadable keychain (E14, Unix).
//!
//! **Comparison.** JSON is compared as text (the file as written), so key order, nulls, messages
//! and argv are exact. Normalization replaces only run-specific values, each by a token:
//! - strings: the lab folder (`<LAB>`: the case, the input, the app cache), fake-leapp's absolute
//!   path (`<FAKE_LEAPP>`), the run id (`<RUN_ID>`), the case id (`<CASE_ID>`), fake-leapp's
//!   SHA-256 (`<FAKE_LEAPP_SHA256>`, checked against `sha2` over the binary), the hash of
//!   `report.sha256` (`<MANIFEST_SHA256>`, checked against `sha2` over the file; the manifest lists
//!   `_lava_data.lava`, which holds absolute paths and a timestamp), fake-leapp's process id in
//!   the glibc loader line (`PYI-<PID>:`, `_MEIfake<PID>`), timestamps (`<TIMESTAMP>`, only strings
//!   in the RFC 3339 `Z` format) and `app.version` (`<APP_VERSION>`);
//! - `tool.platform` (`<PLATFORM>`, only when it is this host's platform key);
//! - `output.seal.total_bytes` (`<TOTAL_BYTES>`, only when it equals the size of the files that
//!   `report.sha256` lists, read from disk: `_lava_data.lava` and, in the cancel rows, the partial
//!   `Screen_Output.html` vary);
//! - `duration_ms` (`<DURATION_MS>`, any integer, also checked against `ended_at − created_at`;
//!   `null` stays).
//!
//! The host is fixed by the test. In `report.sha256` every hash is checked against `sha2` over
//! its file and then replaced by `<SHA256>`; names, order and line format stay exact, and the
//! manifest must list exactly the regular files under `report/`.
//!
//! **Goldens** live in `tests/golden/run/`. A file under `tests/golden/run/<os>/` (`windows`,
//! `linux`) replaces the default (macOS) one on that OS. On a mismatch the normalized actual is
//! printed and written to `<CARGO_TARGET_TMPDIR>/z0a2-actual/<os>/`.
//!
//! Frozen: later bundles do not edit this file or its goldens (SIMPLIFY.md §2).

