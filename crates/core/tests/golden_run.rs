fn os_name() -> &'static str {
    if cfg!(windows) {
        "windows"
    } else if cfg!(target_os = "linux") {
        "linux"
    } else {
        "macos"
    }
}

/// The golden checks of one test: every mismatch is printed (normalized actual) and saved, and
/// the test fails at [`Goldens::finish`].
#[derive(Default)]
struct Goldens {
    mismatches: Vec<String>,
}

impl Goldens {
    /// The golden file of `name` on this OS: the per-OS one if it exists, else the default.
    fn file(name: &str) -> PathBuf {
        let os_file = Path::new(GOLDEN_DIR).join(os_name()).join(name);
        if os_file.is_file() {
            os_file
        } else {
            Path::new(GOLDEN_DIR).join(name)
        }
    }

    fn check(&mut self, name: &str, actual: &str) {
        let file = Self::file(name);
        let expected = fs::read_to_string(&file).ok();
        if expected.as_deref() == Some(actual) {
            return;
        }
        let saved = Path::new(env!("CARGO_TARGET_TMPDIR"))
            .join("z0a2-actual")
            .join(os_name())
            .join(name);
        let _ = fs::create_dir_all(saved.parent().unwrap());
        let _ = fs::write(&saved, actual);
        eprintln!(
            "---- z0a2 golden mismatch: {name} on {} (golden {}{}; actual saved to {}) ----\n\
             {actual}\n---- end of {name} ----",
            os_name(),
            file.display(),
            if expected.is_none() { ", missing" } else { "" },
            saved.display()
        );
        self.mismatches.push(name.to_owned());
    }

    fn finish(self) {
        assert!(
            self.mismatches.is_empty(),
            "golden mismatches on {} (normalized actuals printed above): {:?}",
            os_name(),
            self.mismatches
        );
    }
}

