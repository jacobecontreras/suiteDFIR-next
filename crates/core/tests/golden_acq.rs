fn os_name() -> &'static str {
    if cfg!(windows) {
        "windows"
    } else if cfg!(target_os = "linux") {
        "linux"
    } else {
        "macos"
    }
}

/// The golden checks of one test: every mismatch is printed (normalized actual) and saved, and
/// the test fails at [`Goldens::finish`].
#[derive(Default)]
struct Goldens {
    mismatches: Vec<String>,
}

impl Goldens {
    fn check(&mut self, name: &str, actual: &str) {
        let os_file = Path::new(GOLDEN_DIR).join(os_name()).join(name);
        let file = if os_file.is_file() {
            os_file
        } else {
            Path::new(GOLDEN_DIR).join(name)
        };
        let expected = fs::read_to_string(&file).ok();
        if expected.as_deref() == Some(actual) {
            return;
        }
        let saved = Path::new(env!("CARGO_TARGET_TMPDIR"))
            .join("z0b-actual")
            .join(os_name())
            .join(name);
        let _ = fs::create_dir_all(saved.parent().unwrap());
        let _ = fs::write(&saved, actual);
        eprintln!(
            "---- z0b golden mismatch: {name} on {} (golden {}{}; actual saved to {}) ----\n\
             {actual}\n---- end of {name} ----",
            os_name(),
            file.display(),
            if expected.is_none() { ", missing" } else { "" },
            saved.display()
        );
        self.mismatches.push(name.to_owned());
    }

    fn finish(self) {
        assert!(
            self.mismatches.is_empty(),
            "golden mismatches on {} (normalized actuals printed above): {:?}",
            os_name(),
            self.mismatches
        );
    }
}

// ---- normalization ----

/// What a placeholder accepts.
#[derive(Clone, Copy)]
enum Kind {
    /// A non-negative integer; `null` is kept as it is.
    Count,
    /// An integer 0-100, or `null`.
    PercentOrNull,
}

impl Kind {
    fn accepts(self, raw: &str) -> bool {
        match self {
            Kind::Count => raw.parse::<u64>().is_ok(),
            Kind::PercentOrNull => raw == "null" || raw.parse::<u8>().is_ok_and(|p| p <= 100),
        }
    }
}

/// Normalizes JSON text (see the module doc): known run-specific strings are replaced by tokens,
/// timestamps by `<TIMESTAMP>`, and the placeholder keys' values by their tokens.
struct Normalizer {
    /// Run-specific strings, JSON-escaped, and their tokens; applied in order.
    subs: Vec<(String, &'static str)>,
    /// Keys whose value is a placeholder: key, token, what the value must be.
    placeholders: Vec<(&'static str, &'static str, Kind)>,
}

/// `text` as it appears inside a JSON string.
fn escaped(text: &str) -> String {
    let quoted = serde_json::to_string(text).unwrap();
    quoted[1..quoted.len() - 1].to_owned()
}

/// `YYYY-MM-DDTHH:MM:SSZ`.
fn is_timestamp(text: &str) -> bool {
    let bytes = text.as_bytes();
    bytes.len() == 20
        && bytes.iter().enumerate().all(|(i, b)| match i {
            4 | 7 => *b == b'-',
            10 => *b == b'T',
            13 | 16 => *b == b':',
            19 => *b == b'Z',
            _ => b.is_ascii_digit(),
        })
}

/// The end (exclusive) of the JSON string starting at `start` (its opening quote).
fn string_end(bytes: &[u8], start: usize) -> usize {
    let mut i = start + 1;
    loop {
        match bytes[i] {
            b'\\' => i += 2,
            b'"' => return i + 1,
            _ => i += 1,
        }
    }
}

impl Normalizer {
    fn new() -> Self {
        Self {
            subs: Vec::new(),
            placeholders: vec![
                ("duration_ms", "<DURATION_MS>", Kind::Count),
                ("free_bytes_after", "<FREE_BYTES>", Kind::Count),
            ],
        }
    }

    /// For the records of `case` made with the fake tools in `tools_dir`.
    fn for_case(case: &CreatedCase, tools_dir: &Path) -> Self {
        let mut normalizer = Self::new();
        normalizer.sub(&case.path.to_string_lossy(), "<CASE>");
        normalizer.sub(&tools_dir.to_string_lossy(), "<TOOLS>");
        normalizer.sub(&case.case.case_id, "<CASE_ID>");
        normalizer.sub(&fake_sha256(), "<FAKE_SHA256>");
        normalizer
    }

    fn sub(&mut self, text: &str, token: &'static str) -> &mut Self {
        self.subs.push((escaped(text), token));
        self
    }

    fn acq(mut self, acq_id: &str) -> Self {
        self.sub(acq_id, "<ACQ_ID>");
        self
    }

    /// The cancel rows: the last overall percent depends on when the cancel landed.
    fn cancel_row(mut self) -> Self {
        self.placeholders.push((
            "last_progress_percent",
            "<LAST_PROGRESS_PERCENT>",
            Kind::PercentOrNull,
        ));
        self
    }

    fn value(&self, path: &[String], raw: &str) -> String {
        let key = path.last().map_or("", String::as_str);
        if let Some((_, token, kind)) = self.placeholders.iter().find(|(k, ..)| *k == key) {
            return match kind {
                Kind::Count if raw == "null" => raw.to_owned(),
                _ if kind.accepts(raw) => format!("\"{token}\""),
                _ => raw.to_owned(),
            };
        }
        if !raw.starts_with('"') {
            return raw.to_owned();
        }
        let parent = path.len().checked_sub(2).map(|i| path[i].as_str());
        if parent == Some("app") && key == "version" && raw == format!("\"{APP_VERSION}\"") {
            return "\"<APP_VERSION>\"".to_owned();
        }
        let mut text = raw.to_owned();
        for (from, to) in &self.subs {
            text = text.replace(from.as_str(), to);
        }
        if is_timestamp(&text[1..text.len() - 1]) {
            return "\"<TIMESTAMP>\"".to_owned();
        }
        text
    }

    /// Normalizes JSON text, keeping everything else (layout, key order) byte for byte.
    fn json(&self, text: &str) -> String {
        let bytes = text.as_bytes();
        let mut out = String::with_capacity(text.len());
        // The key of each open object (`[]` for arrays), and whether a key comes next.
        let mut path: Vec<String> = Vec::new();
        let mut objects: Vec<bool> = Vec::new();
        let mut want_key = false;
        let mut i = 0;
        while i < bytes.len() {
            match bytes[i] {
                b'{' | b'[' => {
                    let object = bytes[i] == b'{';
                    objects.push(object);
                    path.push(if object {
                        String::new()
                    } else {
                        "[]".to_owned()
                    });
                    want_key = object;
                    out.push(char::from(bytes[i]));
                    i += 1;
                }
                b'}' | b']' => {
                    objects.pop();
                    path.pop();
                    want_key = false;
                    out.push(char::from(bytes[i]));
                    i += 1;
                }
                b',' => {
                    want_key = objects.last() == Some(&true);
                    out.push(',');
                    i += 1;
                }
                b'"' => {
                    let end = string_end(bytes, i);
                    let raw = &text[i..end];
                    if want_key {
                        *path.last_mut().unwrap() = serde_json::from_str(raw).unwrap();
                        want_key = false;
                        out.push_str(raw);
                    } else {
                        out.push_str(&self.value(&path, raw));
                    }
                    i = end;
                }
                b':' | b' ' | b'\n' | b'\r' | b'\t' => {
                    out.push(char::from(bytes[i]));
                    i += 1;
                }
                _ => {
                    let end = bytes[i..]
                        .iter()
                        .position(|b| matches!(b, b',' | b'}' | b']') || b.is_ascii_whitespace())
                        .map_or(bytes.len(), |n| i + n);
                    out.push_str(&self.value(&path, &text[i..end]));
                    i = end;
                }
            }
        }
        out
    }
}

/// The hash of the fake-idevice binary (the tools are copies of it).
fn fake_sha256() -> String {
    hashing::sha256_file(Path::new(common::FAKE)).unwrap()
}

fn pretty<T: Serialize>(value: &T) -> String {
    let mut text = serde_json::to_string_pretty(value).unwrap();
    text.push('\n');
    text
}

