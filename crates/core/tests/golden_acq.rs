const CRASH_CHILD_DIR: &str = "SUITEDFIR_Z0B_CRASH_CHILD_DIR";

/// The runner that `z0_crash_after_enable` kills.
#[test]
#[ignore = "runs only as the child process of z0_crash_after_enable"]
