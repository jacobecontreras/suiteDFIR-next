/// Waits until `file` exists (at most 20 s).
fn wait_for(file: &Path) {
    let deadline = Instant::now() + Duration::from_secs(20);
    while !file.exists() {
        assert!(
            Instant::now() < deadline,
            "{} never appeared",
            file.display()
        );
        std::thread::sleep(Duration::from_millis(10));
    }
}

/// Cancels once the backup runs and has written its layout (the slow fake writes `backup.pid`
/// right after it), so the partial backup is the same every time.
fn cancel_row(name: &str, scenario: &str) {
    let lab = Lab::new(scenario);
    let pid_file = lab.state.join("backup.pid");
    let mut cancelled = false;
    let (case, outcome, _) = simple(&lab, None, |event, control| {
        if !cancelled
            && let AcqEvent::Log { lines } = event
            && lines.iter().any(|l| l == "Full backup mode.")
        {
            wait_for(&pid_file);
            cancelled = true;
            control.cancel();
        }
    });
    assert!(cancelled);
    let mut goldens = Goldens::default();
    let normalizer = Normalizer::for_case(&case, shared_tools_dir())
        .acq(&outcome.record.acq_id)
        .cancel_row();
    check_acquisition(&mut goldens, name, &acq_dir(&outcome), &normalizer);
    goldens.finish();
}

