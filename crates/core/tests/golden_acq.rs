/// The event sequence without its timing: phases, every log line in order, prompts (at their
/// place among the lines) and the final status. Progress and seal-progress events are left out
/// (their number depends on timing); so are log batch boundaries.
fn event_items(events: &[AcqEvent]) -> Vec<String> {
    let mut items = Vec::new();
    for event in events {
        match event {
            AcqEvent::Phase { phase } => items.push(format!("phase {}", token(phase))),
            AcqEvent::Log { lines } => {
                items.extend(lines.iter().map(|line| format!("line {line}")));
            }
            AcqEvent::DevicePrompt { kind, text } => {
                items.push(format!("prompt {} {text}", token(kind)));
            }
            AcqEvent::Progress { .. } | AcqEvent::SealProgress { .. } => {}
            AcqEvent::Finished { status, .. } => items.push(format!("finished {}", token(status))),
        }
    }
    items
}

/// A contract enum's serialized name.
fn token<T: Serialize>(value: &T) -> String {
    serde_json::to_value(value)
        .unwrap()
        .as_str()
        .unwrap()
        .to_owned()
}

#[test]
fn z0_success_encrypt() {
    let lab = Lab::new("success_encrypt");
    let (case, outcome, events) = simple(&lab, Some(PASSWORD), |_, _| {});
    let mut goldens = Goldens::default();
    let normalizer = Normalizer::for_case(&case, shared_tools_dir()).acq(&outcome.record.acq_id);
    check_acquisition(
        &mut goldens,
        "success_encrypt",
        &acq_dir(&outcome),
        &normalizer,
    );
    let calls = lab.calls();
    goldens.check(
        "success_encrypt.calls.json",
        &calls_text(&calls, &normalizer),
    );

    // commands[i].argv[1..] is exactly what the fake received: encryption on, backup, off.
    let record = &outcome.record;
    let spawned = backup2_calls(&calls);
    assert_eq!(record.commands.len(), 3);
    assert_eq!(spawned.len(), 3, "{spawned:?}");
    for (command, call) in record.commands.iter().zip(&spawned) {
        assert_eq!(command.argv[1..], call[1..], "{:?}", command.purpose);
    }

    // The event order rules: every line is delivered before the next phase, prompt or `finished`
    // event (pinned by the golden sequence), and a prompt event comes right before the log batch
    // that starts with its text.
    for (i, event) in events.iter().enumerate() {
        if let AcqEvent::DevicePrompt { text, .. } = event {
            match events.get(i + 1) {
                Some(AcqEvent::Log { lines }) => assert_eq!(lines.first(), Some(text)),
                other => panic!("after the prompt {text:?} came {other:?}"),
            }
        }
    }
    assert!(matches!(events.last(), Some(AcqEvent::Finished { .. })));
    assert_eq!(
        events
            .iter()
            .filter(|e| matches!(e, AcqEvent::Finished { .. }))
            .count(),
        1
    );
    let items = event_items(&events);
    goldens.check(
        "success_encrypt.events.json",
        &normalizer.json(&pretty(&items)),
    );
    goldens.finish();
}

