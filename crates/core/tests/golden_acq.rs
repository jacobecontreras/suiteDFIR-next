fn running_record(case_dir: &Path) -> Option<AcquisitionRecord> {
    let entry = fs::read_dir(case_dir.join("acquisitions"))
        .ok()?
        .next()?
        .ok()?;
    parse_versioned(&fs::read(entry.path().join("acquisition.json")).ok()?).ok()
}

/// `crash_after_enable`: the runner is killed once the record shows the enable and the backup
/// holding the sync lock (the last rewrite before the backup ends, so the record is the same every
/// time); the next case open recovers it.
#[test]
fn z0_crash_after_enable() {
    let root = tempfile::tempdir().unwrap();
    fs::create_dir_all(root.path().join("state")).unwrap();
    let fields = suitedfir_core::contracts::CaseFields {
        name: "case".to_owned(),
        ..examples::case_fields()
    };
    let case = case::create(root.path(), &fields).unwrap();
    assert_eq!(case.path, root.path().join("case"));
    let mut child = Command::new(std::env::current_exe().unwrap())
        .args(["--exact", "z0_crash_after_enable_child", "--ignored"])
        .env(CRASH_CHILD_DIR, root.path())
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .spawn()
        .unwrap();
    let deadline = Instant::now() + Duration::from_secs(120);
    loop {
        if running_record(&case.path).is_some_and(|r| {
            r.encryption.enabled_by_examiner
                && r.device_changes
                    .iter()
                    .any(|c| c.change == DeviceChangeKind::SyncLockTaken)
        }) {
            break;
        }
        assert!(Instant::now() < deadline, "the backup was never recorded");
        assert!(child.try_wait().unwrap().is_none(), "the child ended early");
        std::thread::sleep(Duration::from_millis(20));
    }
    child.kill().unwrap();
    child.wait().unwrap();
    // On Unix the backup tool (in its own session) outlives the runner; stop it. On Windows the
    // job object took it down with the runner.
    #[cfg(unix)]
    {
        let pid_file = root.path().join("state").join("backup.pid");
        wait_for(&pid_file);
        let pid = fs::read_to_string(&pid_file).unwrap();
        let _ = Command::new("kill").args(["-KILL", pid.trim()]).status();
    }
    let before = running_record(&case.path).unwrap();
    let recovered = acquire::recover_case(&case.path, None, Timestamp::now()).unwrap();
    assert_eq!(recovered, [before.acq_id.as_str()]);
    let dir = acquire::discover(&case.path).unwrap().remove(0).dir;
    let mut goldens = Goldens::default();
    let normalizer = Normalizer::for_case(&case, &root.path().join("tools")).acq(&before.acq_id);
    check_acquisition(&mut goldens, "crash_after_enable", &dir, &normalizer);
    goldens.finish();
}

