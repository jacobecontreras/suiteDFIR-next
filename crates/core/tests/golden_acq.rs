/// Runs an acquisition to the end; `hook` sees every event (and may cancel through the control).
fn acquire_with(
    idevice: &Idevice,
    case: &CreatedCase,
    request: AcqRequest,
    mut hook: impl FnMut(&AcqEvent, &AcqControl),
) -> (AcqOutcome, Vec<AcqEvent>) {
    let job = acquire::start(idevice, request, context(case)).unwrap();
    let control = job.control();
    let mut events = Vec::new();
    let outcome = job.run(&mut |event| {
        hook(&event, &control);
        events.push(event);
    });
    assert_eq!(outcome.write_error, None);
    (outcome, events)
}

/// A new case and an acquisition in it, with the shared fake tools.
fn simple(
    lab: &Lab,
    password: Option<&str>,
    hook: impl FnMut(&AcqEvent, &AcqControl),
) -> (CreatedCase, AcqOutcome, Vec<AcqEvent>) {
    let case = new_case(lab);
    let (outcome, events) = acquire_with(&lab.idevice, &case, request(&case, password), hook);
    (case, outcome, events)
}

fn acq_dir(outcome: &AcqOutcome) -> PathBuf {
    PathBuf::from(&outcome.summary.acq_dir)
}

fn shared_tools_dir() -> &'static Path {
    &common::shared_tools().0
}

/// Checks `<name>.acquisition.json` and, when one was written, `<name>.backup.sha256` (raw).
fn check_acquisition(
    goldens: &mut Goldens,
    name: &str,
    dir: &Path,
    normalizer: &Normalizer,
) -> String {
    let text = fs::read_to_string(dir.join("acquisition.json")).unwrap();
    let normalized = normalizer.json(&text);
    goldens.check(&format!("{name}.acquisition.json"), &normalized);
    if let Ok(manifest) = fs::read_to_string(dir.join(acquire::BACKUP_MANIFEST)) {
        goldens.check(&format!("{name}.backup.sha256"), &manifest);
    }
    normalized
}

/// One scenario row: an acquisition in `scenario` (with encryption when `password` is given),
/// and its golden record.
fn row(name: &str, scenario: &str, password: Option<&str>) {
    let lab = Lab::new(scenario);
    let (case, outcome, _) = simple(&lab, password, |_, _| {});
    let mut goldens = Goldens::default();
    let normalizer = Normalizer::for_case(&case, shared_tools_dir()).acq(&outcome.record.acq_id);
    check_acquisition(&mut goldens, name, &acq_dir(&outcome), &normalizer);
    goldens.finish();
}

/// `lab.calls()` as normalized JSON.
fn calls_text(calls: &[Vec<String>], normalizer: &Normalizer) -> String {
    normalizer.json(&pretty(&calls))
}

/// The fake's recorded `idevicebackup2` calls.
fn backup2_calls(calls: &[Vec<String>]) -> Vec<Vec<String>> {
    calls
        .iter()
        .filter(|call| call[0] == "idevicebackup2")
        .cloned()
        .collect()
}

