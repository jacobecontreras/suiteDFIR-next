/// The fake device's recorded calls in `state_dir`.
fn calls_in(state_dir: &Path) -> Vec<Vec<String>> {
    fs::read(state_dir.join("state.json"))
        .ok()
        .map(|bytes| {
            let state: serde_json::Value = serde_json::from_slice(&bytes).unwrap();
            serde_json::from_value(state["calls"].clone()).unwrap()
        })
        .unwrap_or_default()
}

fn pairing_attempts_in(state_dir: &Path) -> Vec<String> {
    fs::read(state_dir.join("state.json"))
        .ok()
        .map(|bytes| {
            let state: serde_json::Value = serde_json::from_slice(&bytes).unwrap();
            serde_json::from_value(state["pairing_attempts"].clone()).unwrap()
        })
        .unwrap_or_default()
}

#[derive(Serialize)]
struct StartRefusal {
    scenario: &'static str,
    error: AppError,
    acquisitions_created: usize,
    calls: Vec<Vec<String>>,
    pairing_attempts: Vec<String>,
}

/// `acq_start` for the §13.4 rows without an acquisition: the exact error, nothing created, and
/// what was run on the device (never a pairing).
#[test]
fn z0_start_refusals() {
    let mut refusals = Vec::new();
    for scenario in [
        "not_paired",
        "locked",
        "trust_denied",
        "pairing_failed",
        "usbmuxd_missing",
    ] {
        let lab = Lab::new(scenario);
        let case = new_case(&lab);
        let err = acquire::start(&lab.idevice, request(&case, None), context(&case)).unwrap_err();
        refusals.push(StartRefusal {
            scenario,
            error: err.into(),
            acquisitions_created: fs::read_dir(case.path.join("acquisitions"))
                .map(|entries| entries.count())
                .unwrap_or(0),
            calls: lab.calls(),
            pairing_attempts: lab.pairing_attempts(),
        });
        lab.assert_no_temp_dirs();
    }
    let mut goldens = Goldens::default();
    goldens.check(
        "start-refusals.json",
        &Normalizer::new().json(&pretty(&refusals)),
    );
    goldens.finish();
}

#[derive(Serialize)]
struct LaterRefusal {
    case: &'static str,
    error: AppError,
    /// The calls the refused attempt made on the device.
    new_calls: Vec<Vec<String>>,
    pairing_attempts: Vec<String>,
    /// The `encryption-restore*` files in the acquisition folder afterwards.
    attempt_files: Vec<String>,
}

fn attempt_files(dir: &Path) -> Vec<String> {
    let mut names: Vec<String> = fs::read_dir(dir)
        .unwrap()
        .map(|e| e.unwrap().file_name().to_string_lossy().into_owned())
        .filter(|name| name.starts_with("encryption-restore"))
        .collect();
    names.sort();
    names
}

/// An `Idevice` on the shared tools with a fresh fake-device state in `state_dir` (a device the
/// host has no pair record for, in `not_paired`).
fn fresh_device(lab: &Lab, scenario: &str, state_dir: &Path) -> Idevice {
    fs::create_dir_all(state_dir).unwrap();
    let (tools, manifest) = common::shared_tools();
    common::idevice(
        tools,
        manifest.clone(),
        &lab.cache,
        vec![
            ("FAKE_IDEVICE_SCENARIO".into(), scenario.into()),
            ("FAKE_IDEVICE_STATE_DIR".into(), state_dir.into()),
            ("FAKE_IDEVICE_INTERVAL_MS".into(), "5".into()),
        ],
    )
}

/// `restore_later` refusals on every OS: the device gone, not paired, a 3-character password
/// (also with an unpaired device: the password is checked first). Each gives its exact error,
/// writes no attempt file and runs no `encryption off` (nor any pairing).
#[test]
fn z0_restore_later_refusals() {
    let mut refusals = Vec::new();
    let mut refuse = |case_name: &'static str,
                      idevice: &Idevice,
                      state_dir: &Path,
                      case: &CreatedCase,
                      outcome: &AcqOutcome,
                      password: &str| {
        let before = calls_in(state_dir).len();
        let err = acquire::restore_later(
            idevice,
            &case.path,
            &outcome.record.acq_id,
            password.to_owned(),
            &mut |_| {},
        )
        .unwrap_err();
        let new_calls = calls_in(state_dir)[before..].to_vec();
        assert!(
            !new_calls.iter().any(|call| call.iter().any(|a| a == "off")),
            "{case_name}: {new_calls:?}"
        );
        let files = attempt_files(&acq_dir(outcome));
        assert!(files.is_empty(), "{case_name}: {files:?}");
        refusals.push(LaterRefusal {
            case: case_name,
            error: err.into(),
            new_calls,
            pairing_attempts: pairing_attempts_in(state_dir),
            attempt_files: files,
        });
    };

    // The device disconnected during an encrypted backup and is still gone.
    let lab = Lab::new("disconnect");
    let (case, outcome, _) = simple(&lab, Some(PASSWORD), |_, _| {});
    assert_eq!(outcome.summary.warnings, ["encryption_left_enabled"]);
    refuse(
        "device_missing",
        &lab.idevice,
        &lab.state,
        &case,
        &outcome,
        PASSWORD,
    );
    lab.assert_no_temp_dirs();

    // Encryption was left on (restore_fail).
    let lab = Lab::new("restore_fail");
    let (case, outcome, _) = simple(&lab, Some(PASSWORD), |_, _| {});
    // The device has no pair record for this host now.
    let unpaired = lab.root.path().join("state-unpaired");
    refuse(
        "not_paired",
        &fresh_device(&lab, "not_paired", &unpaired),
        &unpaired,
        &case,
        &outcome,
        PASSWORD,
    );
    refuse(
        "password_3_chars",
        &lab.reopen("success"),
        &lab.state,
        &case,
        &outcome,
        "pw!",
    );
    let unpaired_short = lab.root.path().join("state-unpaired-short");
    refuse(
        "password_3_chars_not_paired",
        &fresh_device(&lab, "not_paired", &unpaired_short),
        &unpaired_short,
        &case,
        &outcome,
        "pw!",
    );
    lab.assert_no_temp_dirs();

    let mut goldens = Goldens::default();
    let normalizer = Normalizer::for_case(&case, shared_tools_dir());
    goldens.check(
        "restore-later-refusals.json",
        &normalizer.json(&pretty(&refusals)),
    );
    goldens.finish();
}

