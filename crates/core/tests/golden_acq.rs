#[test]
fn z0_restore_fail() {
    let lab = Lab::new("restore_fail");
    let (case, outcome, _) = simple(&lab, Some(PASSWORD), |_, _| {});
    let mut goldens = Goldens::default();
    let acq_id = outcome.record.acq_id.clone();
    let dir = acq_dir(&outcome);
    let normalizer = Normalizer::for_case(&case, shared_tools_dir()).acq(&acq_id);
    check_acquisition(&mut goldens, "restore_fail", &dir, &normalizer);
    let calls = lab.calls();
    goldens.check("restore_fail.calls.json", &calls_text(&calls, &normalizer));
    let spawned = backup2_calls(&calls);
    assert_eq!(spawned.len(), 3, "{spawned:?}");
    for (command, call) in outcome.record.commands.iter().zip(&spawned) {
        assert_eq!(command.argv[1..], call[1..], "{:?}", command.purpose);
    }

    // Later restores: the device still refuses (attempt 1), then accepts (attempt 2).
    let record_bytes = fs::read(dir.join("acquisition.json")).unwrap();
    for (scenario, file) in [
        ("restore_fail", "encryption-restore.json"),
        ("success", "encryption-restore-2.json"),
    ] {
        let before = lab.calls().len();
        acquire::restore_later(
            &lab.reopen(scenario),
            &case.path,
            &acq_id,
            PASSWORD.to_owned(),
            &mut |_| {},
        )
        .unwrap();
        let text = fs::read_to_string(dir.join(file)).unwrap();
        goldens.check(&format!("restore_fail.{file}"), &normalizer.json(&text));
        // The recorded argv is the `off` call the fake received.
        let attempt: suitedfir_core::contracts::EncryptionRestoreRecord =
            parse_versioned(text.as_bytes()).unwrap();
        let off = backup2_calls(&lab.calls()[before..]);
        assert_eq!(off.len(), 1, "{off:?}");
        assert_eq!(attempt.argv[1..], off[0][1..]);
    }
    // acquisition.json was not modified by the later restores.
    assert_eq!(
        fs::read(dir.join("acquisition.json")).unwrap(),
        record_bytes
    );
    goldens.finish();
}

