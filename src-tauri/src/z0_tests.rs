//! Z0a2 characterizations for S-TOOL (SIMPLIFY.md §3): the exact `AppError`s that candidates S2
//! and S3 move or inline, pinned through entry points no candidate removes (`Jobs::reserve`,
//! `Installs::begin` and the `AppState` command methods).
//!
//! - S3: `run_already_active` from `Jobs::reserve` while the slot is reserved or held, and from
//!   `run_start`, `acq_start` and `temp_cleanup` while a run is active; what `Installs::begin`
//!   returns (it refuses only a second install of the same tool; the job slot does not stop it).
//! - S2: a manifest without an aLEAPP entry: `tool_status` (with and without the dev override),
//!   `tools_status`, `tool_install`, `tool_modules` and `run_start` say "The tool manifest has no
//!   entry for aleapp"; `input_inspect` and `profiles_list` say "Unknown tool".
//!
//! Expected errors are written out here. The helpers are this module's own (never the private
//! ones of `ops/tests.rs` or `replay.rs`). Frozen: later bundles do not edit this file
//! (SIMPLIFY.md §2).

